// ФУНКЦИЯ ПЕРЕВОДА ПОЛЕЙ КАРТОЧЕК
// ============================================
function tc($text) {
    global $texts;
    if (empty($text)) return '';
    if (isset($texts['card_translations'][$text])) {
        return $texts['card_translations'][$text];
    }
    return $text;
}
